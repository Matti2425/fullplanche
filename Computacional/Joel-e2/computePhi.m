function phi = computePhi(N,M,a_n,a_s,a_e,a_w,a_p,b_p,phi_in)
% Author: Joel Campo
% 220311 - Computational Engineering. MUEA
% Assignment 2 (CFD): Generic convection-diffusion transport equation
%
% This function computes the Phi matrix (as a unique output) from the
% inputs of the coefficients and mesh structure

    N = N+2;
    M = M+2;

    phi = zeros(N,M);

    i = 2:N-1;
    j = 2:M-1;
        phi(i, j) = (a_e(i, j) .* phi_in(i+1, j) + ...
                     a_w(i, j) .* phi_in(i-1, j) + ...
                     a_n(i, j) .* phi_in(i, j+1) + ...
                     a_s(i, j) .* phi_in(i, j-1) + ...
                     b_p(i, j)) ./ a_p(i, j);
    clear i j
    % WALLS
    i = 2:N-1;
        phi(i, M) = (a_e(i, M) .* phi_in(i+1, M) + ...
                    a_w(i, M) .* phi_in(i-1, M) + ...
                    a_s(i, M) .* phi_in(i, M - 1) + ...
                    b_p(i, M)) ./ a_p(i, M);

        phi(i, 1) = (a_e(i, 1) .* phi_in(i+1, 1) + ...
                    a_w(i, 1) .* phi_in(i-1, 1) + ...
                    a_n(i, 1) .* phi_in(i, 2) + ...
                    b_p(i, 1)) ./ a_p(i, 1);

    j = 2:M-1;
        phi(1, j) = (a_e(1, j) .* phi_in(2, j) + ...
                    a_n(1, j) .* phi_in(1, j+1) + ...
                    a_s(1, j) .* phi_in(1, j-1) + ...
                    b_p(1, j)) ./ a_p(1, j);

        phi(N, j) = (a_w(N, j) .* phi_in(N-1, j) + ...
                    a_n(N, j) .* phi_in(N, j+1) + ...
                    a_s(N, j) .* phi_in(N, j-1) + ...
                    b_p(N, j)) ./ a_p(N, j);
    clear i j
end